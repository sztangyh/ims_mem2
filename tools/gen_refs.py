# -*- coding: utf-8 -*-
"""生成 `crates/core/src/refs_gen.rs`：把 `moc_ref.json` 的 `match=eq` 边
翻译成"（源表, 源列号, 键类型, 目标表, 目标键列号）"的静态表（P3）。

列号来自本仓库的 `mml_table!` 声明（声明序即列序），参数名 = 字段名大写 / `as ALIAS`。

用法：python tools/gen_refs.py
"""
import io
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MOC_REF = r'C:\dev\ims_ws\data\ims_asset\moc_ref.json'

# 已经"并入"别的表的 MOC（D48 SRVRGT→ASBR 之后没有边的映射需求；这里是 D53 步骤 1）：
# PRALNK 的 12 列按 LINK = PLN 并进 PRATG，参数名不变 → 边跟着改写即可。
# 于是 `PRATG.LINK->PRALNK.PLN` 变成 `PRATG.LINK->PRATG.LINK`，按自环丢掉（正确：
# LINK 变成同一行内的列，不再是跨行引用）。
MERGED = {'PRALNK': 'PRATG'}

# 缺口 10：这些表在**运行期已被并进别的表**（不是列级合并，而是整表不再存在），
# 所以以它们为源的边是死边（0 命中 / 0 悬空 / 只进 missing_table）。
#   SRVRGT → ASBR（P7）：`SRVRGT.IMPU` 落成 ASBR 行的 `SN`，引用检查改在
#   `AsbrShim` 里做（`reg_applied` / `orphan_reg`），由 dnc_stats 打印、验收门断言。
MERGED_AWAY = {'SRVRGT'}


def load_decls():
    """返回 {MOC: [(PARAM, kind_name, col_index)]}；kind ∈ t/n/b/e。"""
    srcs = []
    d = os.path.join(ROOT, 'crates', 'core', 'src', 'schema')
    for fn in os.listdir(d):
        if fn.endswith('.rs'):
            srcs.append(io.open(os.path.join(d, fn), encoding='utf-8').read())
    gen = os.path.join(ROOT, 'crates', 'core', 'src', 'schema_gen_data.rs')
    if os.path.exists(gen):
        srcs.append(io.open(gen, encoding='utf-8').read())

    decls = {}
    pat = re.compile(r'mml_table!\s*\{\s*(?://[^\n]*\n\s*)*([A-Za-z0-9_]+)\s*,\s*([A-Za-z0-9_]+)\s*,'
                     r'(.*?)\n\s*\}', re.S)
    for s in srcs:
        for m in pat.finditer(s):
            moc = m.group(1)
            body = m.group(3)
            fields = []
            col = 0
            for line in body.split('\n'):
                line = line.strip()
                if not line or line.startswith('//') or line.startswith('key'):
                    continue
                mm = re.match(r'(?:pub )?([a-zA-Z_][a-zA-Z0-9_]*)\s*:\s*([A-Za-z0-9_]+)'
                              r'(?:\s*<[^>]*>)?(?:\s+as\s+([A-Za-z0-9_]+))?', line)
                if not mm:
                    continue
                field, ty, alias = mm.group(1), mm.group(2), mm.group(3)
                param = (alias or field).upper()
                kind = {'Text': 't', 'Pfx': 't', 'PfxText': 't', 'Enum': 'e',
                        'Bool': 'b', 'Ip': 'w', 'Eid': 'w', 'Bits': 'w',
                        'Pair': 'w', 'Spc': 'w'}.get(ty, 'n')
                fields.append((param, kind, col))
                col += 1
                if ty in ('Pfx', 'PfxText'):
                    # A3：`Pfx` 列会注入伴生列 `<NAME>_NUM`（宏里自动加），列号要跟着跳一格
                    fields.append((param + '_NUM', 'N', col))
                    col += 1
            if fields:
                decls[moc] = fields
    return decls


def main():
    decls = load_decls()
    print('已解析声明:', len(decls), '张表')
    edges = json.load(io.open(MOC_REF, encoding='utf-8'))
    out, skipped = [], {'no_from': 0, 'no_to': 0, 'no_col': 0, 'kind': 0, 'self': 0,
                        'merged': 0}
    merged_dead = []
    seen = set()
    for e in edges:
        if e['match'] != 'eq':
            continue
        fm, fp = e['moc'], e['param'].upper()
        tm, tp = e['ref_moc'], (e['ref_param'] or '').upper()
        fm, tm = MERGED.get(fm, fm), MERGED.get(tm, tm)
        if fm in MERGED_AWAY:
            merged_dead.append(f'{fm}.{fp}->{tm}.{tp}')
            skipped['merged'] += 1
            continue
        if fm not in decls:
            skipped['no_from'] += 1
            continue
        if tm not in decls:
            skipped['no_to'] += 1
            continue
        if fm == tm:
            skipped['self'] += 1
            continue
        fcols = {p: (k, i) for (p, k, i) in decls[fm]}
        tcols = {p: (k, i) for (p, k, i) in decls[tm]}
        if fp not in fcols or tp not in tcols:
            skipped['no_col'] += 1
            continue
        (fk, fc), (tk, tc) = fcols[fp], tcols[tp]
        # 只消费同类型（文本↔文本 / 数字↔数字 / 宽值↔宽值）；枚举按文本比
        if fk != tk:
            skipped['kind'] += 1
            continue
        key = (fm, fp, tm, tp)
        if key in seen:
            continue
        seen.add(key)
        out.append(dict(from_moc=fm, from_col=fc, to_moc=tm, to_col=tc,
                        kind={'t': 'sym', 'w': 'wide'}.get(fk, 'num'),
                        label=f'{fm}.{fp}->{tm}.{tp}', ref_kind=e['kind']))
    print('可物化边:', len(out), '跳过:', skipped)
    if merged_dead:
        print('  源表已并入（死边，已剔除）:', merged_dead)

    lines = ['// @generated by tools/gen_refs.py —— 不要手改',
             '//! `moc_ref.json` 的 `match=eq` 边，已翻译成列号（P3 Ref 物化）。',
             '', '/// 一条引用边：源表某列的取值 = 目标表键列的取值。',
             '#[derive(Debug, Clone, Copy)]',
             'pub struct EdgeDef {',
             '    pub from: &\'static str,',
             '    pub from_col: u16,',
             '    pub to: &\'static str,',
             '    pub to_col: u16,',
             '    /// `true` = 文本（符号）比较，`false` = 数值比较',
             '    pub sym: bool,',
             '    /// A2.5：`true` = 宽值比较（`Ip/Eid/Bits` 走 u64 池）',
             '    pub wide: bool,',
             '    pub label: &\'static str,',
             '}', '', 'pub static EDGES: &[EdgeDef] = &[']
    for e in out:
        lines.append('    EdgeDef { from: "%s", from_col: %d, to: "%s", to_col: %d, sym: %s, wide: %s, label: "%s" },'
                     % (e['from_moc'], e['from_col'], e['to_moc'], e['to_col'],
                        'true' if e['kind'] == 'sym' else 'false',
                        'true' if e['kind'] == 'wide' else 'false', e['label']))
    lines += ['];', '']
    dst = os.path.join(ROOT, 'crates', 'core', 'src', 'refs_gen.rs')
    io.open(dst, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))
    print('写入', dst)


if __name__ == '__main__':
    main()

